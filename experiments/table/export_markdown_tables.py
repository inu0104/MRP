"""Render the paper's LaTeX tables as a Markdown results page.

The files under ``paper/table/`` are machine-generated by the table scripts, so
their structure is regular enough to parse directly. Deriving RESULTS.md from
them (rather than transcribing the numbers by hand) keeps the Markdown and the
published tables from drifting apart.

Usage:
    python3 experiments/table/export_markdown_tables.py
    python3 experiments/table/export_markdown_tables.py --check
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
TABLE_DIR = REPO_ROOT / "paper" / "table"
DEFAULT_OUTPUT = REPO_ROOT / "paper" / "README.md"

# Markdown cannot span columns, so the two widest tables are emitted as one
# narrow table per metric group instead of a single table that scrolls
# sideways. ``keys`` are the identifying columns repeated in every part;
# each entry of ``parts`` is (title, column indices).
SPLITS: dict[str, dict] = {
    "main_mrp_table.tex": {
        "keys": [0, 1],
        "parts": [
            ("Base calibrator (unchanged by MRP)", [2, 3]),
            ("NLL_correct ↓", [4, 5, 6]),
            ("AUPR-Error ↑", [7, 8, 9]),
            ("AURC ↓", [10, 11, 12]),
        ],
    },
    "simplex_projection.tex": {
        "keys": [0, 1, 2],
        "parts": [
            ("Fixed ECE ↓", [3, 4, 5]),
            ("Top ECE ↓", [6, 7, 8]),
            ("NLL ↓", [9, 10, 11]),
            ("Brier ↓", [12, 13, 14]),
            ("Feasibility", [15, 16]),
        ],
    },
}

# \shortstack wraps a long dataset name onto two lines, which loses the
# separator between them. Restore the canonical spelling these datasets use
# everywhere else in the paper. Cosmetic only -- no numeric cell is touched.
NAME_FIXUPS = {
    "ESCI-Rerank US": "ESCI-Rerank-US",
}

# Shorter column labels, using the abbreviations the paper already uses.
HEADER_ABBREVIATIONS = {
    "NLL_correct↓": "C-NLL",
    "AUPR-Error↑": "AUPR-E",
    "AURC↓": "AURC",
    "Fixed ECE↓": "Fixed ECE",
    "Top ECE↓": "Top ECE",
    "NLL↓": "NLL",
    "Brier↓": "Brier",
    "ΔSelAcc@τ": "Δ",
}

# Order follows the order the tables appear in the paper.
TABLES = [
    ("datasets.tex", "Datasets"),
    ("main_mrp_table.tex", "Main Reliability Results"),
    ("budgeted_fallback.tex", "Budgeted Fallback"),
    ("label_conditional_residual.tex", "Label-conditioned Reliability Spread"),
    ("mrp_ablation_results.tex", "Structural Ablations"),
    ("simplex_projection.tex", "Top-label Simplex Projection"),
]

SYMBOLS = {
    r"\downarrow": "↓",
    r"\uparrow": "↑",
    r"\Delta": "Δ",
    r"\delta": "δ",
    r"\times": "×",
    r"\tau": "τ",
    r"\pm": "±",
    r"\varnothing": "∅",
    r"\le": "≤",
    r"\ge": "≥",
    r"\approx": "≈",
    r"\ldots": "…",
    r"\%": "%",
    r"\&": "&",
    r"\_": "_",
}

# Commands whose single argument should be kept verbatim.
UNWRAP = ["mathrm", "mathcal", "text", "textbf", "textit", "emph", "hat", "shortstack", "improve", "mrcimprove"]
# Commands that should be dropped along with their argument.
DROP_WITH_ARG = ["citep", "cite", "citet", "label", "ref"]
# Structural commands with no argument that carry no content.
DROP_BARE = [
    "toprule", "midrule", "bottomrule", "centering", "small", "scriptsize",
    "footnotesize", "tiny", "normalsize", "hline",
]

BOLD_COMMANDS = ("textbf", "improve", "mrcimprove")


def find_matching_brace(text: str, open_index: int) -> int:
    """Return the index of the '}' matching the '{' at ``open_index``."""
    depth = 0
    for i in range(open_index, len(text)):
        if text[i] == "{":
            depth += 1
        elif text[i] == "}":
            depth -= 1
            if depth == 0:
                return i
    raise ValueError("unbalanced braces")


def extract_command_arg(text: str, command: str, start: int = 0) -> tuple[int, int, str] | None:
    """Find ``\\command{...}`` and return (start, end_exclusive, argument)."""
    pattern = re.compile(r"\\" + command + r"\s*\{")
    match = pattern.search(text, start)
    if match is None:
        return None
    open_index = match.end() - 1
    close_index = find_matching_brace(text, open_index)
    return match.start(), close_index + 1, text[open_index + 1 : close_index]


def split_top_level(text: str, separator: str) -> list[str]:
    """Split on ``separator`` occurrences that sit outside any brace group."""
    parts: list[str] = []
    depth = 0
    buffer: list[str] = []
    i = 0
    while i < len(text):
        char = text[i]
        if char == "{":
            depth += 1
        elif char == "}":
            depth -= 1
        if depth == 0 and text.startswith(separator, i):
            parts.append("".join(buffer))
            buffer = []
            i += len(separator)
            continue
        buffer.append(char)
        i += 1
    parts.append("".join(buffer))
    return parts


def clean_cell(text: str) -> str:
    """Turn one LaTeX cell into Markdown-safe inline text."""
    text = text.strip()

    bold = any(re.search(r"\\" + name + r"\s*\{", text) for name in BOLD_COMMANDS)

    for command in DROP_WITH_ARG:
        while True:
            found = extract_command_arg(text, command)
            if found is None:
                break
            start, end, _ = found
            text = text[:start] + text[end:]

    # Unwrap keeps the argument; repeat until no nested wrappers remain.
    changed = True
    while changed:
        changed = False
        for command in UNWRAP:
            found = extract_command_arg(text, command)
            if found is None:
                continue
            start, end, argument = found
            text = text[:start] + argument + text[end:]
            changed = True

    text = text.replace(r"\\", " ")
    for source, target in SYMBOLS.items():
        text = text.replace(source, target)

    text = re.sub(r"\\(" + "|".join(DROP_BARE) + r")\b", "", text)
    text = re.sub(r"\\addlinespace(\[[^\]]*\])?", "", text)
    text = re.sub(r"\\cmidrule(\([^)]*\))?\{[^}]*\}", "", text)
    text = re.sub(r"\\setlength\{[^}]*\}\{[^}]*\}", "", text)
    text = text.replace(r"\(", "").replace(r"\)", "").replace("$", "")
    text = re.sub(r"\\[a-zA-Z]+\s*", "", text)
    text = text.replace("{", "").replace("}", "")
    text = text.replace("--", "–")
    text = text.replace("~", " ")
    text = text.replace("|", r"\|")
    text = re.sub(r"\s+", " ", text).strip()
    text = re.sub(r"\s*±\s*", "±", text)  # keep "0.832±0.000" in one narrow cell
    text = re.sub(r"(\w)- (\w)", r"\1-\2", text)  # "MSLR- WEB10K" -> "MSLR-WEB10K"
    text = NAME_FIXUPS.get(text, text)

    if bold and text:
        text = f"**{text}**"
    return text


def expand_multicolumn(cells: list[str]) -> list[str]:
    """Replace ``\\multicolumn{n}{..}{text}`` with text plus n-1 blank cells."""
    expanded: list[str] = []
    for cell in cells:
        match = re.match(r"\s*\\multicolumn\s*\{(\d+)\}\s*\{[^}]*\}\s*\{", cell)
        if match is None:
            expanded.append(cell)
            continue
        open_index = match.end() - 1
        close_index = find_matching_brace(cell, open_index)
        span = int(match.group(1))
        expanded.append(cell[open_index + 1 : close_index])
        expanded.extend([""] * (span - 1))
    return expanded


def strip_rules(cell: str) -> str:
    """Drop the rule commands LaTeX puts at the start of a row's first cell."""
    cell = re.sub(r"\\(top|mid|bottom)rule", "", cell)
    cell = re.sub(r"\\cmidrule(\([^)]*\))?\{[^}]*\}", "", cell)
    cell = re.sub(r"\\addlinespace(\[[^\]]*\])?", "", cell)
    return cell.strip()


def strip_multirow(cell: str) -> str:
    """Return the visible content of a ``\\multirow{n}{*}{text}`` cell."""
    match = re.match(r"\s*\\multirow\s*\{\d+\}\s*\{[^}]*\}\s*\{", cell)
    if match is None:
        return cell
    open_index = match.end() - 1
    close_index = find_matching_brace(cell, open_index)
    return cell[open_index + 1 : close_index]


def is_rule_only(row: str) -> bool:
    stripped = re.sub(r"\\(top|mid|bottom)rule|\\cmidrule(\([^)]*\))?\{[^}]*\}|\\addlinespace(\[[^\]]*\])?|\s", "", row)
    return stripped == ""


def parse_table(source: str) -> tuple[str, list[list[str]], list[list[str]]]:
    """Return (caption, header rows, body rows) for one LaTeX table."""
    caption_found = extract_command_arg(source, "caption")
    caption = clean_cell(caption_found[2]) if caption_found else ""

    begin = re.search(r"\\begin\{tabular\}\s*(\[[^\]]*\])?\s*\{", source)
    if begin is None:
        raise ValueError("no tabular environment found")
    spec_close = find_matching_brace(source, begin.end() - 1)
    end = source.index(r"\end{tabular}", spec_close)
    body = source[spec_close + 1 : end]

    # The header is everything before the first \midrule.
    split_at = body.find(r"\midrule")
    header_source, body_source = (body[:split_at], body[split_at:]) if split_at != -1 else ("", body)

    def rows_of(chunk: str) -> list[list[str]]:
        rows = []
        for raw in split_top_level(chunk, r"\\"):
            if is_rule_only(raw):
                continue
            cells = expand_multicolumn([strip_rules(cell) for cell in split_top_level(raw, "&")])
            cleaned = [clean_cell(strip_multirow(cell)) for cell in cells]
            if any(cell for cell in cleaned):
                rows.append(cleaned)
        return rows

    return caption, rows_of(header_source), rows_of(body_source)


def merge_header(header_rows: list[list[str]], width: int) -> list[str]:
    """Flatten a multi-level LaTeX header into one Markdown header row."""
    if not header_rows:
        return [""] * width
    merged: list[str] = []
    for column in range(width):
        # A \multicolumn spans blanks to its right, so carry the last label forward.
        parts: list[str] = []
        for row_index, row in enumerate(header_rows):
            label = row[column] if column < len(row) else ""
            # Only a \multicolumn group in an upper row spans into blank cells;
            # a blank in the final sub-header row means the column has no label.
            if not label and row_index < len(header_rows) - 1:
                for index in range(min(column, len(row) - 1), -1, -1):
                    if row[index]:
                        label = row[index] if _spans(row, index, column) else ""
                        break
            parts.append(label)
        seen: list[str] = []
        for part in parts:
            if part and part not in seen:
                seen.append(part)
        merged.append(" ".join(seen))
    return merged


def _spans(row: list[str], start: int, column: int) -> bool:
    """True when row[start] is a group label whose blanks reach ``column``."""
    return all(not row[i] for i in range(start + 1, min(column + 1, len(row))))


def fill_down(rows: list[list[str]], width: int) -> list[list[str]]:
    """Repeat grouped values that LaTeX rendered once via \\multirow."""
    filled: list[list[str]] = []
    carry = [""] * width
    for row in rows:
        padded = row + [""] * (width - len(row))
        out = []
        for column in range(width):
            value = padded[column]
            if value:
                carry[column] = value
            elif column < 2:  # only leading grouping columns are carried
                value = carry[column]
            out.append(value)
        filled.append(out)
    return filled


def shorten(label: str) -> str:
    for long, short in HEADER_ABBREVIATIONS.items():
        label = label.replace(long, short)
    return label.strip()


def render_grid(header: list[str], body: list[list[str]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join([" --- "] * len(header)) + "|"]
    lines.extend("| " + " | ".join(row) + " |" for row in body)
    return "\n".join(lines)


def to_markdown(
    caption: str,
    header_rows: list[list[str]],
    body_rows: list[list[str]],
    split: dict | None = None,
) -> str:
    width = max((len(row) for row in header_rows + body_rows), default=0)
    if width == 0:
        return ""
    header = [shorten(label) for label in merge_header(header_rows, width)]
    body = fill_down(body_rows, width)

    blocks = [caption, ""] if caption else []
    if split is None:
        blocks.append(render_grid(header, body))
        return "\n".join(blocks)

    keys = split["keys"]
    for title, columns in split["parts"]:
        indices = keys + columns
        part_header = [header[i] for i in indices]
        part_body = [[row[i] for i in indices] for row in body]
        blocks.append(f"**{title}**")
        blocks.append("")
        blocks.append(render_grid(part_header, part_body))
        blocks.append("")
    return "\n".join(blocks).rstrip()


def build_document() -> str:
    parts = [
        "# Paper Artifacts and Results",
        "",
        "`table/` holds the LaTeX tables and `figure/` the figures used in",
        "*Post-Calibration Reliability Reranking of Relevance Decisions via",
        "Label-wise Monotone Projection* (CIKM '26). Both are regenerated by",
        "`experiments/table/run_fixed_decision_mrp_main.sh`.",
        "",
        "The tables are reproduced below so they can be read without LaTeX. This",
        "page is generated from `table/*.tex` by",
        "`experiments/table/export_markdown_tables.py`, so it always matches the",
        "published numbers. The `.tex` files are the source of truth. Bold marks",
        "the same entries the paper highlights.",
        "",
        "Markdown cannot span columns, so multi-level headers are flattened and",
        "the two widest tables are split into one table per metric group.",
        "",
    ]
    for filename, title in TABLES:
        path = TABLE_DIR / filename
        if not path.exists():
            raise FileNotFoundError(path)
        caption, header_rows, body_rows = parse_table(path.read_text(encoding="utf-8"))
        parts.append(f"## {title}")
        parts.append("")
        parts.append(to_markdown(caption, header_rows, body_rows, SPLITS.get(filename)))
        parts.append("")
    return "\n".join(parts).rstrip() + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit non-zero if the output file is missing or stale",
    )
    args = parser.parse_args()

    document = build_document()
    if args.check:
        current = args.output.read_text(encoding="utf-8") if args.output.exists() else ""
        if current != document:
            print(f"{args.output} is out of date; rerun without --check")
            return 1
        print(f"{args.output} is up to date")
        return 0

    args.output.write_text(document, encoding="utf-8")
    print(args.output)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
